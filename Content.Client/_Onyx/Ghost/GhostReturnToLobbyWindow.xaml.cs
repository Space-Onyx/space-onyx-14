using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Onyx.Ghost;

[GenerateTypedNameReferences]
public sealed partial class GhostReturnToLobbyWindow : DefaultWindow
{
    private static readonly TimeSpan ConfirmDelay = TimeSpan.FromSeconds(3);

    [Dependency] private IGameTiming _timing = default!;

    private TimeSpan _openedAt;
    private bool _canConfirm;

    public event Action? OnConfirm;

    public GhostReturnToLobbyWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _openedAt = _timing.RealTime;
        ConfirmButton.OnPressed += _ => OnConfirm?.Invoke();
        UpdateConfirmButton();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateConfirmButton();
    }

    public void SetCanConfirm(bool canConfirm)
    {
        _canConfirm = canConfirm;
        ConfirmButton.Text = Loc.GetString(canConfirm
            ? "ghost-return-to-lobby-confirm"
            : "ghost-return-to-lobby-insufficient-playtime");
        UpdateConfirmButton();
    }

    private void UpdateConfirmButton()
    {
        var delayElapsed = _timing.RealTime - _openedAt >= ConfirmDelay;
        ConfirmButton.Disabled = !(_canConfirm && delayElapsed);
    }
}

[GenerateTypedNameReferences]
[Virtual]
public partial class FancyVendingMachineMenu : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPlayerManager _playerManager = default!;

    private readonly Dictionary<EntProtoId, EntityUid> _dummies = [];
    private readonly List<FancyVendingMachineData> _cachedItems = [];

    public event Action<VendingMachineInventoryEntry>? OnItemSelected;
    public Action? OnWithdraw;

    private double _priceMultiplier = 1;
    private bool _infiniteStock;
    protected bool UsesIdCardMiningPoints;
    private int _credits;
    private string _balanceLabel = string.Empty;
    private readonly SharedIdCardSystem _idCardSystem;

    public Color ButtonBorderColor = Color.FromHex("#4972A1");
    public Color ButtonBaseColor = Color.FromHex("#141F2F");
    public Color ButtonHoveredColor = Color.FromHex("#4972A1");
    public Color ButtonDisabledColor = Color.FromHex("#3f3f3fff");

    public FancyVendingMachineMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        DarkBackground.PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex("#141519") };
        _idCardSystem = _entityManager.System<IdCardSystem>();
        SearchBar.OnTextChanged += _ => PopulateList();
        WithdrawButton.OnPressed += _ => OnWithdraw?.Invoke();
    }

    public override void Close()
    {
        base.Close();

        // Delete any dummy items we spawned
        foreach (var entity in _dummies.Values)
        {
            _entityManager.QueueDeleteEntity(entity);
        }
        _dummies.Clear();
    }

    private bool DataFilterCondition(string filter, FancyVendingMachineData data)
    {
        if (string.IsNullOrEmpty(filter))
            return true;

        return data.Name.Contains(filter, StringComparison.CurrentCultureIgnoreCase);
    }

    /// <summary>
    /// Populates the list of available items on the vending machine interface
    /// and sets icons based on their prototypes
    /// </summary>
    public void Populate(EntityUid entityUid, List<VendingMachineInventoryEntry> inventory, double priceMultiplier, int credits,
        bool showWithdraw, string balanceLabel, bool infiniteStock, bool usesIdCardMiningPoints = false)
    {
        _cachedItems.Clear();
        _infiniteStock = infiniteStock;
        UsesIdCardMiningPoints = usesIdCardMiningPoints;
        _balanceLabel = balanceLabel;
        _credits = usesIdCardMiningPoints ? GetLocalMiningPoints() : credits;
        _priceMultiplier = _entityManager.GetComponentOrNull<VendingMachineComponent>(entityUid)?.AllForFree ?? true ? 0 : priceMultiplier;

        if (_entityManager.TryGetComponent<VendingMachineComponent>(entityUid, out var comp))
        {
            ButtonBaseColor = comp.UiButtonBaseColor;
            ButtonBorderColor = comp.UiButtonBorderColor;
            ButtonHoveredColor = comp.UiButtonHoveredColor;
            ButtonDisabledColor = comp.UiButtonDisabledColor;
        }

        CreditsLabel.Text = Loc.GetString(balanceLabel, ("credits", _credits));
        WithdrawButton.Visible = showWithdraw;
        WithdrawButton.Disabled = _credits == 0;

        if (inventory.Count == 0 && VendingContents.Visible)
        {
            SearchBar.Visible = false;
            VendingContents.Visible = false;

            var outOfStockLabel = new Label()
            {
                Text = Loc.GetString("vending-machine-component-try-eject-out-of-stock"),
                Margin = new Thickness(4, 4),
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Stretch,
                HorizontalAlignment = HAlignment.Center
            };

            MainContainer.AddChild(outOfStockLabel);

            return;
        }

        for (var i = 0; i < inventory.Count; i++)
        {
            var entry = inventory[i];

            if (!_dummies.TryGetValue(entry.ID, out var dummy))
            {
                dummy = _entityManager.Spawn(entry.ID);
                _dummies.Add(entry.ID, dummy);
            }

            StringBuilder sb = new(entry.OverrideName == null
                ? Identity.Name(dummy, _entityManager)
                : Loc.GetString(entry.OverrideName));
            sb[0] = char.ToUpper(sb[0]);

            _cachedItems.Add(new FancyVendingMachineData(sb.ToString(), entry));
        }

        PopulateList();
    }

    private void PopulateList()
    {
        VendingContents.RemoveAllChildren();

        var filter = SearchBar.Text;
        var filtered = _cachedItems.Where(item => DataFilterCondition(filter, item)).ToList(); // <Onyx-VendingMechanicsReview-edited>

        if (filtered.All(item => item.Entry.Category == null))
        {
            var grid = CreateGrid();
            VendingContents.AddChild(grid);
            AddItems(grid, filtered);
            return;
        }

        filtered = filtered.OrderBy(item => item.Entry.Order).ToList(); // <Onyx-VendingMechanicsReview>

        foreach (var category in filtered.Select(item => item.Entry.Category).Distinct())
        {
            var items = filtered.Where(item => item.Entry.Category == category).ToList();

            var header = CreateCategoryHeader(category == null
                ? Loc.GetString("vending-ui-category-other")
                : Loc.GetString(category));
            VendingContents.AddChild(header);

            var grid = CreateGrid();
            VendingContents.AddChild(grid);
            AddItems(grid, items);
        }
    }

    protected virtual Control CreateCategoryHeader(string text)
    {
        var panel = new PanelContainer
        {
            Margin = new Thickness(8, 12, 8, 4),
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#292c32"),
                BorderColor = Color.FromHex("#4b515b"),
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 8,
                ContentMarginTopOverride = 4,
                ContentMarginBottomOverride = 4,
            },
        };
        panel.AddChild(new Label { Text = text, StyleClasses = { "LabelHeading" } });
        return panel;
    }

    private static GridContainer CreateGrid()
    {
        return new GridContainer
        {
            Columns = 6,
            HorizontalExpand = true,
            HorizontalAlignment = HAlignment.Left, // <Onyx-VendingMechanicsReview-edited>
        };
    }

    private void AddItems(GridContainer grid, List<FancyVendingMachineData> items)
    {
        foreach (var item in items)
        {
            var price = (int)(item.Entry.Price * _priceMultiplier);
            var affordable = !UsesIdCardMiningPoints || price <= _credits;
            var listItem = new FancyVendingMachineItem(item.Entry.ID, item.Name, (int)item.Entry.Amount, price,
                _infiniteStock, affordable, UsesIdCardMiningPoints);
            listItem.BuyPressed += () => OnItemSelected?.Invoke(item.Entry);

            grid.AddChild(listItem);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!UsesIdCardMiningPoints)
            return;

        var credits = GetLocalMiningPoints();
        if (credits == _credits)
            return;

        _credits = credits;
        CreditsLabel.Text = Loc.GetString(_balanceLabel, ("credits", _credits));
        PopulateList();
    }

    private int GetLocalMiningPoints()
    {
        if (_playerManager.LocalEntity is not { } player ||
            !_idCardSystem.TryFindIdCard(player, out var card) ||
            !_entityManager.TryGetComponent<MiningPointsComponent>(card, out var points))
        {
            return 0;
        }

        return points.Points;
    }

    private record struct FancyVendingMachineData(string Name, VendingMachineInventoryEntry Entry);
}

